def _transcript(config: dict[str, Any], row: dict[str, str], transcript_text: str) -> dict[str, Any]:
    source = config["source_path"]
    return {
        "transcript_id": config["transcript_id"],
        "session_id": config["session_id"],
        "case_id": config["case_id"],
        "owner_user_id": "user_therapist_001",
        "original_filename": Path(source).name,
        "transcript_text": transcript_text,
        "review_status": "awaiting_review",
        "qa_status": "pass",
        "qa_score": 100,
        "qa_issues": [],
        "reviewer_notes": f"Generated from {source}; Reference Cohort Label={row['group']}.",
        "created_at": f"{config['date']}T09:15:00Z",
        "updated_at": f"{config['date']}T10:00:00Z",
    }


def _select_utterances(utterances: list[Any]) -> list[Any]:
    return utterances[:MAX_UTTERANCES_PER_TRANSCRIPT]


def _lines(config: dict[str, Any], utterances: list[Any]) -> list[dict[str, Any]]:
    rows = []
    for index, utterance in enumerate(utterances, start=1):
        rows.append(
            {
                "line_id": f"{config['transcript_id']}_L{index:04d}",
                "transcript_id": config["transcript_id"],
                "session_id": config["session_id"],
                "case_id": config["case_id"],
                "owner_user_id": "user_therapist_001",
                "line_number": index,
                "speaker": utterance.speaker_code,
                "speaker_role": utterance.speaker_role,
                "text": utterance.raw_text,
                "utterance_text": utterance.raw_text,
                "confidence": 1.0,
                "timing": _timing(utterance),
                "start_ms": utterance.start_ms,
                "end_ms": utterance.end_ms,
                "review_status": "needs_review",
                "reviewed": False,
            }
        )
    return rows


def _feature_output(config: dict[str, Any], row: dict[str, str], utterances: list[Any]) -> dict[str, Any]:
    extracted = extract_clinical_features(
        [utterance.to_normalized_line(session_id=config["session_id"]) for utterance in utterances],
        age_months=_number(row.get("age_months", 0)),
    )
    features = {feature: extracted["features"].get(feature, 0) for feature in FEATURES}
    return {
        "feature_id": config["feature_id"],
        "session_id": config["session_id"],
        "case_id": config["case_id"],
        "owner_user_id": "user_therapist_001",
        "feature_schema_version": "14-feature-schema",
        "extraction_status": "completed",
        "created_at": f"{config['date']}T09:20:00Z",
        "features": features,
        "source": {
            "source_path": config["source_path"],
            "corpus": row["corpus"],
            "reference_cohort_label": row["group"],
            "task_type": row["task_type"],
            "mock_scope": f"first {MAX_UTTERANCES_PER_TRANSCRIPT} main CHAT tiers",
        },
    }


def _ai_output(config: dict[str, Any], row: dict[str, str]) -> dict[str, Any]:
    probabilities = config["probabilities"]
    most_similar = max(probabilities, key=probabilities.get)
    source = config["source_path"]
    return {
        "output_id": config["output_id"],
        "session_id": config["session_id"],
        "case_id": config["case_id"],
        "owner_user_id": "user_therapist_001",
        "concern_level": "watchful_review" if most_similar != "TD" else "no_concern",
        "screening_support_score": round(float(probabilities[most_similar]), 2),
        "reference_cohort_probabilities": probabilities,
        "most_similar_reference_cohort": most_similar,
        "reference_cohort_label": row["group"],
        "inference_status": "preliminary",
        "report_eligible": False,
        "top_contributing_features": ["mluw", "ttr", "unintelligible_ratio"],
        "evidence_items": [
            f"Source transcript: {source}",
            f"Reference cohort label retained from corpus metadata: {row['group']}",
            "Preliminary mock output; review transcript context before interpretation.",
        ],
        "explanation": (
            f"This mock output shows reference cohort similarity for {Path(source).name}. "
            "It is clinical decision support only and is not a diagnosis."
        ),
        "therapist_review_status": "awaiting_review",
        "created_at": f"{config['date']}T09:25:00Z",
    }


def _vocab(utterances: list[Any]) -> list[dict[str, Any]]:
    tokens = [
        token
        for utterance in utterances
        if utterance.speaker_role == "child"
        for token in utterance.tokens
    ]
    return [
        {"word": word, "count": count, "type": "token", "isNew": False}
        for word, count in Counter(tokens).most_common(12)
    ]


def _chat_text(parsed: Any, utterances: list[Any]) -> str:
    lines = ["@Begin"]
    for header_key in ["@Languages", "@Participants", "@ID", "@Types"]:
        for value in parsed.headers.get(header_key, []):
            lines.append(f"{header_key}:\t{value}")
    for utterance in utterances:
        lines.append(f"*{utterance.speaker_code}:\t{utterance.raw_text}")
    lines.append("@End")
    return "\n".join(lines)


def _timing(utterance: Any) -> dict[str, float | None] | None:
    if utterance.start_ms is None and utterance.end_ms is None:
        return None
    return {
        "start_time": utterance.start_ms / 1000 if utterance.start_ms is not None else None,
        "end_time": utterance.end_ms / 1000 if utterance.end_ms is not None else None,
    }


def _sex(value: str) -> str:
    normalized = value.strip().lower()
    if normalized in {"male", "female"}:
        return normalized
    return "not_specified"


def _number(value: Any) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0.0
    return int(number) if number.is_integer() else number


def _js(value: Any) -> str:
    return re.sub(r'"([A-Za-z_$][A-Za-z0-9_$]*)":', r"\1:", json.dumps(value, ensure_ascii=True, indent=2))


if __name__ == "__main__":
    main()
