def main() -> None:
    feature_rows = _load_feature_rows()
    cases: list[str] = []
    sessions: list[str] = []
    transcript_lines: dict[str, list[dict[str, Any]]] = {}
    transcript_records: dict[str, str] = {}
    feature_outputs: dict[str, dict[str, Any]] = {}
    ai_outputs: dict[str, dict[str, Any]] = {}
    session_vocabs: dict[str, list[dict[str, Any]]] = {}

    for config in SELECTED_TRANSCRIPTS:
        source_path = config["source_path"]
        row = feature_rows[source_path]
        parsed = parse_cha_file(PROJECT_ROOT / source_path)
        utterances = _select_utterances(parsed.utterances)
        case = _case(config, row)
        session = _session(config)
        transcript_text = _chat_text(parsed, utterances)

        cases.append(f"  createChildCase({_js(case)})")
        sessions.append(f"  createSession({_js(session)})")
        transcript_lines[config["session_id"]] = _lines(config, utterances)
        transcript_records[config["session_id"]] = (
            f"createTranscript({_js(_transcript(config, row, transcript_text))})"
        )
        feature_outputs[config["session_id"]] = _feature_output(config, row, utterances)
        ai_outputs[config["session_id"]] = _ai_output(config, row)
        session_vocabs[config["session_id"]] = _vocab(utterances)

    OUTPUT_PATH.write_text(
        "\n".join(
            [
                "// Generated by scripts/build_cha_reference_mock_data.py.",
                "// Derived from local CHAT (.cha) reference transcripts for mock-mode demos.",
                "",
                "import { createChildCase, createSession, createTranscript } from \"@shared/models\";",
                "",
                "export const mockChaReferenceCases = [",
                ",\n".join(cases),
                "];",
                "",
                "export const mockChaReferenceSessions = [",
                ",\n".join(sessions),
                "];",
                "",
                f"export const mockChaReferenceTranscriptLines = {_js(transcript_lines)};",
                "",
                "export const mockChaReferenceTranscriptRecords = {",
                ",\n".join(
                    f"  {json.dumps(session_id)}: {factory}"
                    for session_id, factory in transcript_records.items()
                ),
                "};",
                "",
                f"export const mockChaReferenceExtractedFeatureOutputs = {_js(feature_outputs)};",
                "",
                f"export const mockChaReferenceAiDecisionOutputs = {_js(ai_outputs)};",
                "",
                f"export const mockChaReferenceSessionVocabs = {_js(session_vocabs)};",
                "",
            ]
        ),
        encoding="utf-8",
    )


def _load_feature_rows() -> dict[str, dict[str, str]]:
    with FEATURES_CSV.open(newline="", encoding="utf-8") as handle:
        return {row["source_path"]: row for row in csv.DictReader(handle)}


def _case(config: dict[str, Any], row: dict[str, str]) -> dict[str, Any]:
    group = row["group"]
    source = config["source_path"]
    return {
        "case_id": config["case_id"],
        "owner_user_id": "user_therapist_001",
        "anonymized_child_code": f"REF-{row['corpus'].upper()}-{Path(source).stem}",
        "display_label": f"{row['corpus']} {Path(source).stem} reference sample",
        "age_months": int(round(float(row["age_months"]))),
        "sex": _sex(row["sex"]),
        "primary_concerns": (
            f"Reference cohort sample from {row['corpus']} ({row['task_type']}, cohort {group}). "
            "Use for mock workflow review only; not a diagnosis."
        ),
        "external_clinical_status": "not_provided",
        "consent_status": "granted",
        "anonymization_status": "anonymized",
        "support_level": config["support_level"],
        "latest_score": config["latest_score"],
        "score_trend": [round(max(config["latest_score"] - 0.08, 0), 2), config["latest_score"]],
        "starred": False,
        "notes": (
            f"Source .cha: {source}. Reference Cohort Label={group}; "
            "label is retained for cohort comparison context only."
        ),
        "created_at": f"{config['date']}T09:00:00Z",
        "updated_at": f"{config['date']}T10:00:00Z",
    }


